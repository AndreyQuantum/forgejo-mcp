// Command docgen writes docs/TOOLS.md from the tool registry.
//
// Usage: go run ./internal/tools/docgen [-o docs/TOOLS.md] [-check]
//
// With -check the file is not written; the command exits 1 when the existing
// file differs from the generated text.
package main

import (
	"bytes"
	"flag"
	"fmt"
	"os"
	"strings"

	"github.com/AndreyQuantum/forgejo-mcp/internal/config"
	"github.com/AndreyQuantum/forgejo-mcp/internal/tools"
	"github.com/AndreyQuantum/forgejo-mcp/internal/tools/all"
)

func main() {
	out := flag.String("o", "docs/TOOLS.md", "output file")
	check := flag.Bool("check", false, "fail when the output file is out of date instead of writing it")
	flag.Parse()

	doc, err := Generate()
	if err != nil {
		fmt.Fprintln(os.Stderr, "docgen:", err)
		os.Exit(1)
	}
	if *check {
		cur, err := os.ReadFile(*out)
		if err != nil || !bytes.Equal(cur, []byte(doc)) {
			fmt.Fprintf(os.Stderr, "docgen: %s is out of date; run `make docs`\n", *out)
			os.Exit(1)
		}
		return
	}
	if err := os.WriteFile(*out, []byte(doc), 0o644); err != nil {
		fmt.Fprintln(os.Stderr, "docgen:", err)
		os.Exit(1)
	}
}

// Generate renders the tool reference for every tool of every toolset.
func Generate() (string, error) {
	r := tools.NewRegistry()
	all.RegisterAll(r)
	cfg := config.Defaults()
	cfg.Toolsets = "all"
	if err := r.Build(cfg); err != nil {
		return "", err
	}
	return Render(r.Enabled()), nil
}

// Render formats specs as Markdown. The output is deterministic.
func Render(specs []tools.Spec) string {
	var b strings.Builder
	b.WriteString("# Tool reference\n\n")
	b.WriteString("Generated by `make docs` from the tool registry. Do not edit by hand.\n\n")

	actions := 0
	for _, s := range specs {
		actions += len(s.Actions)
	}
	fmt.Fprintf(&b, "%d tools, %d actions. Toolsets: `meta` is always on; `admin` is off by default.\n\n", len(specs), actions)

	b.WriteString("| Tool | Toolset | Actions | Description |\n|---|---|---|---|\n")
	for _, s := range specs {
		fmt.Fprintf(&b, "| [`%s`](#%s) | %s | %d | %s |\n", s.Name, s.Name, s.Toolset, len(s.Actions), cell(s.Description))
	}
	b.WriteString("\n")

	for _, s := range specs {
		fmt.Fprintf(&b, "## %s\n\n", s.Name)
		fmt.Fprintf(&b, "%s\n\nToolset: `%s`.", s.Description, s.Toolset)
		if s.RepoScoped {
			b.WriteString(" Repo-scoped: `repo` is optional when it can be detected from the working directory or `FORGEJO_REPO`.")
		}
		b.WriteString("\n\n")
		b.WriteString("| Action | Mode | Summary | Parameters |\n|---|---|---|---|\n")
		for _, a := range s.Actions {
			fmt.Fprintf(&b, "| `%s` | %s | %s | %s |\n", a.Name, modeName(a.Mode, a.ModeFor != nil), cell(a.Summary), params(a))
		}
		b.WriteString("\n")
	}
	return b.String()
}

func modeName(m tools.Mode, dynamic bool) string {
	if dynamic {
		return "per call"
	}
	switch m {
	case tools.Write:
		return "write"
	case tools.Destructive:
		return "destructive"
	}
	return "read"
}

func params(a tools.Action) string {
	req := map[string]bool{}
	for _, n := range a.Required {
		req[n] = true
	}
	var parts []string
	for _, n := range a.Params {
		if req[n] {
			parts = append(parts, "`"+n+"`*")
		} else {
			parts = append(parts, "`"+n+"`")
		}
	}
	for _, n := range a.Required {
		found := false
		for _, p := range a.Params {
			found = found || p == n
		}
		if !found {
			parts = append(parts, "`"+n+"`*")
		}
	}
	return strings.Join(parts, ", ")
}

func cell(s string) string {
	s = strings.ReplaceAll(s, "|", "\\|")
	return strings.Join(strings.Fields(s), " ")
}
